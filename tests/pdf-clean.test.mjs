import { PDFDocument, rgb, StandardFonts } from "pdf-lib";
import QRCode from "qrcode";

function formatPdfInr(amount) {
  return `INR ${Number(amount || 0).toLocaleString("en-IN")}`;
}

function cleanText(str) {
  if (!str) return "";
  return str
    .replace(/₹/g, "INR ")
    .replace(/[^\x20-\x7E\xA0-\xFF]/g, " ");
}

async function testPdfGeneration() {
  const sampleData = {
    regId: "SF26-F72342",
    ticketNo: "SFT-98A7B6",
    name: "Samaira Goyal",
    phone: "9778803677",
    email: "sportsfestivalindia@illusorydesignstudios.com",
    category: "Powerlifting · Raw Open · Under 65kg",
    amount: 1,
    utr: "123456789012",
    verifyUrl: "https://sportsfestivalindia.com/verify-ticket/test-token",
    isTest: true,
  };

  // Test Receipt
  const docR = await PDFDocument.create();
  const pageR = docR.addPage([595.28, 841.89]);
  const fontR = await docR.embedFont(StandardFonts.Helvetica);
  pageR.drawText(cleanText(`Amount: ${sampleData.isTest ? "INR 1.00 (Test Fee)" : formatPdfInr(sampleData.amount)}`), { font: fontR });
  const bytesR = await docR.save();
  console.log("Receipt PDF generated bytes:", bytesR.length);

  // Test Ticket
  const docT = await PDFDocument.create();
  const pageT = docT.addPage([595.28, 841.89]);
  const fontT = await docT.embedFont(StandardFonts.Helvetica);
  pageT.drawText(cleanText(`Ticket Pass: ${sampleData.name} - ${formatPdfInr(sampleData.amount)}`), { font: fontT });
  const bytesT = await docT.save();
  console.log("Ticket PDF generated bytes:", bytesT.length);
}

testPdfGeneration().catch(err => console.error(err));

